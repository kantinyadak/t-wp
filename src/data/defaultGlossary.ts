/**
 * Parse CSV line handling commas within quotes or standard delimiters
 */
export function parseGlossaryCsv(csvText: string, source: 'default' | 'sheet' | 'custom' = 'default'): GlossaryTerm[] {
  const lines = csvText.split(/\r?\n/);
  const terms: GlossaryTerm[] = [];
  
  // Skip header if en,fa
  let startIndex = 0;
  if (lines.length > 0 && lines[0].toLowerCase().includes('en') && lines[0].toLowerCase().includes('fa')) {
    startIndex = 1;
  }

  for (let i = startIndex; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) continue;

    // Simple CSV parser supporting quoted values
    const parts: string[] = [];
    let current = '';
    let inQuotes = false;
    for (let c = 0; c < line.length; c++) {
      const char = line[c];
      if (char === '"') {
        if (inQuotes && line[c + 1] === '"') {
          current += '"';
          c++;
        } else {
          inQuotes = !inQuotes;
        }
      } else if (char === ',' && !inQuotes) {
        parts.push(current.trim());
        current = '';
      } else {
        current += char;
      }
    }
    parts.push(current.trim());

    if (parts.length < 2) continue;

    const en = parts[0];
    const fa = parts[1];
    if (!en || !fa) continue;

    const pos = parts[2] || 'term';
    const description = parts[3] || '';

    // Extract primary Persian term (before comma or pipe or slash)
    const alternates = fa.split(/[،|/]/).map(s => s.trim()).filter(Boolean);
    const primaryFa = alternates[0] || fa;

    terms.push({
      id: `${source}-${en.toLowerCase().replace(/[^a-z0-9]/g, '_')}-${i}`,
      en: en.trim(),
      fa: fa.trim(),
      primaryFa: primaryFa.trim(),
      alternates,
      pos: pos.trim(),
      description: description.trim(),
      isOfficial: true,
      source,
      updatedAt: Date.now(),
    });
  }

  return terms;
}

export const INITIAL_GLOSSARY = parseGlossaryCsv(RAW_GLOSSARY_CSV, 'default');
